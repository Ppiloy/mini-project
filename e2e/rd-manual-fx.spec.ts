import { expect, test } from "@playwright/test";
import ExcelJS from "exceljs";
import { mkdir } from "node:fs/promises";
import { dirname } from "node:path";

test("manual BOT conversion stays explicit, editable and reproducible in the saved report", async ({ page }, testInfo) => {
  await page.goto("/demo");
  await page.getByRole("button", { name: "ผู้เสียภาษี" }).click();
  await page.getByRole("button", { name: "เริ่มคำนวณใหม่" }).click();
  await page.getByLabel("ปีภาษี (พ.ศ.)").selectOption("2568");
  await page.getByLabel("ปีที่เกิดเงินได้ (ค.ศ.)").fill("2025");
  await page.getByRole("button", { name: "เพิ่มปีที่เกิดเงินได้" }).click();
  await page.getByLabel("รูปแบบข้อมูลวันพำนัก").selectOption("declared");
  await page.getByRole("button", { name: "ถัดไป", exact: true }).click();
  await page.getByRole("button", { name: "เพิ่มแหล่งเงินได้แรก" }).click();
  const source = page.locator(".source-card").first();
  await source.getByRole("combobox", { name: /ประเทศแหล่งเงินได้/ }).fill("US");
  await page.getByRole("option", { name: /สหรัฐอเมริกา \(US\)/ }).click();
  await source.getByRole("combobox", { name: /ประเภทเงินได้/ }).selectOption("40_1");
  await source.getByLabel(/^วันที่เกิดเงินได้/).fill("2025-01-01");
  await source.getByLabel(/^รูปแบบจำนวนเงิน/).selectOption("original_currency");
  await source.getByLabel(/^วันที่นำเงินเข้าไทย/).fill("2025-10-01");
  await expect(source.getByLabel("วิธีอ้างอิงอัตราแลกเปลี่ยน")).toHaveValue("bot_average_buying");
  await source.getByRole("textbox", { name: /^จำนวนเงินได้ในต่างประเทศ \(D\)/ }).fill("1000");
  await source.getByRole("textbox", { name: /^จำนวนภาษีชำระในต่างประเทศ \(E\)/ }).fill("100");
  await source.getByRole("textbox", { name: /^จำนวนเงินได้ในต่างประเทศที่นำเข้ามาในประเทศ \(F\)/ }).fill("500");
  await source.getByLabel("อัตราแลกเปลี่ยน (บาทต่อ 1 USD)").fill("36.15");
  await source.getByLabel("วันที่อ้างอิงอัตราแลกเปลี่ยน").fill("2025-10-01");
  await expect(source.getByText(/อัตราอ้างอิง ธปท. ต้องเป็นวันทำการก่อนวันที่นำเงินเข้าไทย/)).toBeVisible();
  await source.getByLabel("วันที่อ้างอิงอัตราแลกเปลี่ยน").fill("2025-09-30");
  await source.getByLabel("แหล่งอัตราที่ผู้ใช้ระบุ").fill("ธปท. อัตราเฉลี่ยรับซื้อ 30 ก.ย. 2568");
  const breakdown = source.getByRole("region", { name: "การแปลงจำนวนเงินเป็นบาท" });
  await expect(breakdown).toContainText("36,150.00");
  await expect(breakdown).toContainText("3,615.00");
  await expect(breakdown).toContainText("18,075.00");
  await expect(source.getByText("อัตราที่ผู้ใช้กรอกเอง ยังไม่ผ่านการตรวจสอบโดยต้นแบบ", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "บันทึกร่าง", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "บันทึกแล้ว" })).toBeVisible();
  await page.reload();
  await page.getByRole("button", { name: "ถัดไป", exact: true }).click();
  await expect(source.getByLabel("วันที่อ้างอิงอัตราแลกเปลี่ยน")).toHaveValue("2025-09-30");
  await expect(source.getByLabel("อัตราแลกเปลี่ยน (บาทต่อ 1 USD)")).toHaveValue("36.15");
  await page.getByRole("button", { name: "ถัดไป", exact: true }).click();
  await page.locator("#case-domesticAssessableIncome").fill("0");
  await page.locator("#case-thaiTax-amountBeforeFtc").fill("100000");
  await page.getByRole("button", { name: "ถัดไป", exact: true }).click();
  await page.getByRole("button", { name: "ถัดไป", exact: true }).click();
  await page.getByRole("checkbox", { name: "ยืนยันจำนวนภาษีไทยก่อนเครดิต (L)" }).check();
  await page.getByRole("checkbox", { name: "ยืนยันจำนวนภาษีต่างประเทศ (E) · แหล่งเงินได้ 1" }).check();
  await page.getByRole("button", { name: "คำนวณเครดิตภาษี", exact: true }).click();
  await expect(page.getByText("1,807.50").first()).toBeVisible();
  await page.getByRole("link", { name: "ดูรายงาน", exact: true }).click();
  await expect(page.locator(".worksheet-original-currency").first()).toContainText("36.15");
  await expect(page.locator(".worksheet-original-currency").first()).toContainText("30 ก.ย. 2568");
  await expect(page.locator(".worksheet-original-currency").first()).toContainText("ธปท. อัตราเฉลี่ยรับซื้อ 30 ก.ย. 2568");
  await expect(page.locator(".worksheet-original-currency").first()).toContainText("สิ้นวันทำการก่อนวันที่นำเงินเข้าไทย");
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "ส่งออก Excel", exact: true }).click();
  const download = await downloadPromise;
  const path = testInfo.outputPath("manual-bot.xlsx");
  await mkdir(dirname(path), { recursive: true });
  await download.saveAs(path);
  const workbook = new ExcelJS.Workbook();
  await workbook.xlsx.readFile(path);
  const cells: unknown[] = [];
  workbook.getWorksheet("ผลคำนวณ")!.eachRow((row) => row.eachCell((cell) => cells.push(cell.value)));
  expect(cells).toContain(1000);
  expect(cells).toContain(36150);
  expect(cells).toContain(3615);
  expect(cells).toContain(18075);
  expect(cells).toContain("2025-09-30");
  expect(cells).toContain("ธปท. อัตราเฉลี่ยรับซื้อ 30 ก.ย. 2568");
  expect(cells).toContain("อัตราเฉลี่ยรับซื้อของธนาคารแห่งประเทศไทย");
  expect(cells).toContain("อัตราที่ผู้ใช้กรอกเอง ยังไม่ผ่านการตรวจสอบโดยต้นแบบ");
});
